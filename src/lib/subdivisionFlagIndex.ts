/** Vite base URL — resolves to "/" in dev and "/<repo>/" on GitHub Pages. */
const LOCAL_BASE = `${import.meta.env.BASE_URL}flags/sub`;

/**
 * Returns the bundled URL of the flag for the given ISO 3166-2 subdivision code,
 * or null if no flag is bundled. (Kept under its historical name; it no longer
 * touches any CDN.)
 */
export function subdivisionFlagCdnUrl(isoCode: string): string | null {
  const key = isoCode.toUpperCase().replace(/_/g, "-");
  if (!FLAG_CODES.has(key)) return null;
  const cc = key.split("-")[0]!;
  const ext = NON_SVG_EXT[key] ?? "svg";
  return `${LOCAL_BASE}/${cc}/${key}.${ext}`;
}

export function hasSubdivisionFlag(isoCode: string): boolean {
  return FLAG_CODES.has(isoCode.toUpperCase().replace(/_/g, "-"));
}
