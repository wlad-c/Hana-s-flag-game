// Generates src/data/passportColors.ts — each country's PREDOMINANT passport
// cover colour, for the Learn world-map passport control's "Passport cover
// colours" option (🛂 dropdown next to the 🚩 flag overlay).
//
// SOURCED, never fabricated: the colour is the dominant colour of the country's
// OWN bundled ordinary-passport cover image (the same file the National-symbols
// tab and the grid's "Passports" view show — src/data/nationalFlags.ts), read
// with sharp's histogram. A passport cover is a solid background behind a small
// emblem, so the dominant colour IS the background/predominant colour the owner
// asked for. We never invent a colour: a country with no bundled ordinary
// passport simply gets no entry, and the map leaves it the neutral land colour.
//
// Re-run:  node scripts/build-passport-colors.mjs
// (needs the bundled passport images under public/national-flags/**; no network.)

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import sharp from "sharp";
import { NATIONAL_FLAGS } from "../src/data/nationalFlags.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT = resolve(ROOT, "src/data/passportColors.ts");

function toHex({ r, g, b }) {
  return (
    "#" +
    [r, g, b].map((x) => Math.max(0, Math.min(255, x)).toString(16).padStart(2, "0")).join("")
  );
}

/** The ordinary passport for a country: the first passport entry that carries a
 *  bundled image (the ordinary cover leads the section — see CLAUDE.md rule 4a).
 *  A `noImageReason` passport (no path) yields no colour. */
function ordinaryPassportPath(flags) {
  const p = flags.find((f) => f.category === "passport" && f.path);
  return p?.path ?? null;
}

const rows = [];
let missing = 0;
for (const [code, flags] of Object.entries(NATIONAL_FLAGS)) {
  const rel = ordinaryPassportPath(flags);
  if (!rel) {
    missing++;
    continue;
  }
  const abs = resolve(ROOT, "public", rel);
  let buf;
  try {
    buf = await readFile(abs);
  } catch {
    console.warn(`  ! ${code}: passport image not bundled (${rel}) — skipped`);
    missing++;
    continue;
  }
  // density lifts SVG rasterisation to a usable resolution; ignored for raster.
  const { dominant } = await sharp(buf, { density: 150 }).stats();
  rows.push([code, toHex(dominant)]);
}

rows.sort(([a], [b]) => a.localeCompare(b));

const body = rows.map(([code, hex]) => `  ${JSON.stringify(code)}: ${JSON.stringify(hex)},`).join("\n");

const out = `// GENERATED by scripts/build-passport-colors.mjs — DO NOT EDIT BY HAND.
// Re-run: node scripts/build-passport-colors.mjs
//
// Each country's PREDOMINANT passport-cover colour, used by the Learn world map's
// "colour countries by passport" layer (the 🛂 toggle beside the 🚩 flag overlay).
// The colour is the dominant colour of the country's OWN bundled ordinary-passport
// cover image (src/data/nationalFlags.ts → public/national-flags/**), extracted by
// the generator — it is never hand-written or approximated. A country with no
// bundled ordinary passport is absent here, and the map leaves it the neutral land
// colour rather than inventing one.

/** ISO 3166-1 alpha-2 country code → predominant passport-cover colour (hex). */
export const PASSPORT_COLORS: Readonly<Record<string, string>> = {
${body}
};
`;

await writeFile(OUT, out, "utf8");
console.log(`Wrote ${OUT}`);
console.log(`  ${rows.length} passport colour(s); ${missing} country(ies) without a bundled ordinary passport.`);
