#!/usr/bin/env node
/**
 * Generates src/data/migrantOrigins.ts from the committed UN DESA bilateral extract.
 *
 * Source (never fabricated):
 *   United Nations DESA Population Division — International Migrant Stock 2024
 *   Table 1 (Destination and origin), mid-year 2024, both sexes combined.
 *   https://www.un.org/development/desa/pd/content/international-migrant-stock
 *   Workbook: undesa_pd_2024_ims_stock_by_sex_destination_and_origin.xlsx
 *
 * Bundled extract: scripts/data/undesa-ims-2024-bilateral-iso2.csv
 *   (destination,origin,stock_2024) for UN members / permanent observers only.
 *   Re-extract from the official xlsx with:
 *     node scripts/extract-undesa-migrant-bilateral.mjs [path/to.xlsx]
 *
 * A missing origin for a destination is NOT stored as 0 — UN DESA often folds
 * residual origins into an "Others" aggregate, so an absent pair means no
 * country-level figure was published. Listed zeros are kept as zeros.
 *
 * Re-run: node scripts/build-migrant-origins.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CSV = resolve(__dirname, "data/undesa-ims-2024-bilateral-iso2.csv");
const OUT = resolve(ROOT, "src/data/migrantOrigins.ts");
const UN_CODES_FILE = resolve(ROOT, "src/lib/unMemberStates.ts");

const SOURCE = {
  name: "United Nations DESA Population Division — International Migrant Stock 2024",
  page: "https://www.un.org/development/desa/pd/content/international-migrant-stock",
  workbook:
    "https://www.un.org/development/desa/pd/sites/www.un.org.development.desa.pd/files/undesa_pd_2024_ims_stock_by_sex_destination_and_origin.xlsx",
  citation:
    "United Nations Department of Economic and Social Affairs, Population Division (2024). International Migrant Stock 2024.",
  licence: "CC BY 3.0 IGO",
  edition: "2024 (mid-year estimates)",
  year: 2024,
  csvPath: "scripts/data/undesa-ims-2024-bilateral-iso2.csv",
};

function loadUnCodes(src) {
  const m = src.match(/UN_MEMBER_CODES[\s\S]*?=[\s\S]*?new Set\(\[([\s\S]*?)\]\)/);
  if (!m) throw new Error("Could not parse UN_MEMBER_CODES from unMemberStates.ts");
  const codes = [...m[1].matchAll(/"([A-Z]{2})"/g)].map((x) => x[1]);
  if (codes.length !== 195) {
    throw new Error(`Expected 195 UN codes, got ${codes.length}`);
  }
  return new Set(codes);
}

const unCodes = loadUnCodes(readFileSync(UN_CODES_FILE, "utf8"));
const csvBytes = readFileSync(CSV);
const csvSha = createHash("sha256").update(csvBytes).digest("hex");
const lines = csvBytes.toString("utf8").trim().split(/\r?\n/);
const header = lines[0];
if (header !== "destination,origin,stock_2024") {
  throw new Error(`Unexpected CSV header: ${header}`);
}

/** @type {Map<string, Map<string, number>>} */
const byDest = new Map();
let skippedNonUn = 0;
let skippedSelf = 0;

for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line) continue;
  const [destRaw, originRaw, stockRaw] = line.split(",");
  const dest = destRaw?.trim().toUpperCase();
  const origin = originRaw?.trim().toUpperCase();
  const stock = Number(stockRaw);
  if (!dest || !origin || !Number.isFinite(stock) || stock < 0 || !Number.isInteger(stock)) {
    throw new Error(`Malformed CSV line ${i + 1}: ${line}`);
  }
  if (!unCodes.has(dest) || !unCodes.has(origin)) {
    skippedNonUn++;
    continue;
  }
  if (dest === origin) {
    skippedSelf++;
    continue;
  }
  let origins = byDest.get(dest);
  if (!origins) {
    origins = new Map();
    byDest.set(dest, origins);
  }
  if (origins.has(origin)) {
    throw new Error(`Duplicate pair ${dest}←${origin}`);
  }
  origins.set(origin, stock);
}

if (skippedNonUn) {
  console.warn(`Skipped ${skippedNonUn} non-UN rows`);
}
if (skippedSelf) {
  console.warn(`Skipped ${skippedSelf} self pairs`);
}

const sortedDests = [...byDest.keys()].sort();
const body = sortedDests
  .map((d) => {
    const origins = [...byDest.get(d).entries()].sort(([a], [b]) => a.localeCompare(b));
    const inner = origins
      .map(([o, n]) => `    ${JSON.stringify(o)}: ${n},`)
      .join("\n");
    return `  ${JSON.stringify(d)}: {\n${inner}\n  },`;
  })
  .join("\n");

const pairCount = [...byDest.values()].reduce((n, m) => n + m.size, 0);

const out = `// GENERATED by scripts/build-migrant-origins.mjs — DO NOT EDIT BY HAND.
// Re-run: node scripts/build-migrant-origins.mjs
//
// Bilateral international migrant stock (people born in origin, living in
// destination) at mid-year 2024 for the Learn world-map "Migrant origins"
// colour mode. SOURCED from UN DESA International Migrant Stock 2024 Table 1;
// never hand-written or approximated. An origin absent from a destination's
// map is NOT zero — UN DESA did not publish a country-level figure for that
// pair (residual stock may sit in an "Others" aggregate).
//
// Source: ${SOURCE.name}
// Page: ${SOURCE.page}
// Workbook: ${SOURCE.workbook}
// Citation: ${SOURCE.citation}
// Licence: ${SOURCE.licence}
// Edition: ${SOURCE.edition}
// Bundled CSV: ${SOURCE.csvPath}
// CSV sha256: ${csvSha}

/** Provenance for the bundled migrant-origin matrix. */
export const MIGRANT_ORIGINS_SOURCE = {
  name: ${JSON.stringify(SOURCE.name)},
  page: ${JSON.stringify(SOURCE.page)},
  workbook: ${JSON.stringify(SOURCE.workbook)},
  citation: ${JSON.stringify(SOURCE.citation)},
  licence: ${JSON.stringify(SOURCE.licence)},
  edition: ${JSON.stringify(SOURCE.edition)},
  year: ${SOURCE.year},
  csvPath: ${JSON.stringify(SOURCE.csvPath)},
  csvSha256: ${JSON.stringify(csvSha)},
} as const;

/**
 * destination ISO alpha-2 → origin ISO alpha-2 → migrant stock (integer).
 * Self (destination === origin) is omitted; the overlay paints the selected
 * destination black itself. Only UN members / permanent observers appear.
 */
export const MIGRANT_ORIGINS: Readonly<
  Record<string, Readonly<Record<string, number>>>
> = {
${body}
};
`;

writeFileSync(OUT, out);
console.log(
  `Wrote ${OUT} — ${sortedDests.length} destinations, ${pairCount} origin pairs (sha ${csvSha.slice(0, 12)}…)`,
);
